#!/usr/bin/env node
/**
 * Generates src/data/realmDrillTotals.ts with the total number of drill
 * moves per opening (kingdom), used for accurate per-realm progress meters.
 *
 * Counts moves in *-main.json drill packs, mapped to kingdoms using the same
 * prefix logic as KingdomPanel's "Available drills" filter.
 */
import { readdirSync, readFileSync, writeFileSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const DRILL_DIR = join(__dirname, '..', 'public', 'drill-data');
const OUT_FILE = join(__dirname, '..', 'src', 'data', 'realmDrillTotals.ts');

// Kingdom -> file ID prefixes (must match KingdomPanel's DRILLS filter)
const KINGDOM_PREFIXES = {
  italian: ['giuoco-pianissimo', 'evans-gambit', 'two-knights', 'fried-liver-attack', 'giuoco-piano', 'greco', 'traxler-counter-attack', 'ulvestad-variation'],
  sicilian: ['sicilian-'],
  spanish: ['ruy-lopez-'],
  english: ['english-'],
  scandinavian: ['scandinavian-', 'scandi-'],
  queendom: ['queen-', 'slav-', 'budapest-', 'blackmar-', 'london-'],
  french: ['french-'],
  dutch: ['dutch-'],
  germany: ['caro-', 'german-'],
};

// Kingdom -> openingId (from mapLocations MAP_LOCATIONS)
const KINGDOM_OPENING = {
  italian: 'italian',
  sicilian: 'sicilian',
  spanish: 'spanish',
  english: 'english',
  scandinavian: 'scandinavian',
  queendom: 'queendom',
  french: 'french',
  dutch: 'dutch',
  germany: 'germany',
};

function kingdomForFileId(fileId) {
  // fileId like 'giuoco-pianissimo-main' -> base 'giuoco-pianissimo'
  const base = fileId.replace(/-main$/, '');
  for (const [kingdom, prefixes] of Object.entries(KINGDOM_PREFIXES)) {
    if (prefixes.some(p => base === p || base.startsWith(p))) return kingdom;
  }
  return null;
}

const totals = {}; // openingId -> total moves
const files = readdirSync(DRILL_DIR).filter(f => f.endsWith('-main.json'));

for (const file of files) {
  const fileId = file.replace(/\.json$/, '');
  const kingdom = kingdomForFileId(fileId);
  if (!kingdom) {
    console.log(`  skip (no kingdom): ${fileId}`);
    continue;
  }
  const openingId = KINGDOM_OPENING[kingdom];
  const data = JSON.parse(readFileSync(join(DRILL_DIR, file), 'utf8'));
  let moves = 0;
  for (const line of data.lines || []) {
    moves += (line.moves || []).length;
  }
  totals[openingId] = (totals[openingId] || 0) + moves;
  console.log(`  ${openingId}: +${moves} moves (${fileId})`);
}

const ts = `/**
 * Total drill moves per opening (realm), generated by scripts/compute-realm-totals.mjs.
 * Used for per-realm progress meters. DO NOT EDIT MANUALLY.
 */
export const REALM_TOTAL_MOVES: Record<string, number> = ${JSON.stringify(totals, null, 2)};
`;

writeFileSync(OUT_FILE, ts);
console.log(`\nWrote ${OUT_FILE}`);
console.log('Totals:', totals);

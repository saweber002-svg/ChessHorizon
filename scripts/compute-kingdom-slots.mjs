#!/usr/bin/env node
/**
 * Generates src/data/kingdomSlots.ts — the per-variation move-slot sets the
 * story-progression cleared predicates (shared/progressRules.ts) evaluate.
 *
 * Slot derivation mirrors DrillSession: a slot is one global move index of
 * the variation's main line; its side is whose turn that ply is (sides
 * alternate from the pack startFen's active color). Variation membership
 * mirrors getKingdomDrills (src/data/kingdomDrills.ts): Italian variations
 * come from the curated ITALIAN_DRILL_VARIATIONS list; other kingdoms take
 * production-visible *-main packs by file-id prefix, minus the demoted
 * tactic variations. Tactical/puzzle/deviation packs never contribute slots.
 *
 * Re-run after any change to the drill registry, mapLocations' Italian list,
 * the demoted set, or main-pack move lists:  node scripts/compute-kingdom-slots.mjs
 */
import { readFileSync, writeFileSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const DRILL_DIR = join(ROOT, 'public', 'drill-data');
const OUT_FILE = join(ROOT, 'src', 'data', 'kingdomSlots.ts');

function extractIds(tsPath, exportName) {
  const src = readFileSync(tsPath, 'utf8');
  const start = src.indexOf(exportName);
  if (start < 0) throw new Error(`${exportName} not found in ${tsPath}`);
  const open = src.indexOf('[', start);
  const close = src.indexOf(']', open);
  const body = src.slice(open, close);
  return [...body.matchAll(/'([^']+)'/g)].map((m) => m[1]);
}

const ALL_IDS = extractIds(join(ROOT, 'src/data/drillRegistry.ts'), 'ALL_DRILL_FILE_IDS');

// Must mirror DEMOTED_TACTIC_VARIATION_IDS in src/data/kingdomDrills.ts.
const DEMOTED = new Set([
  'fried-liver-attack',
  'traxler-counter-attack',
  'ulvestad-variation',
  'moeller-attack',
  'dutch-staunton-gambit',
  'scandinavian-icelandic-gambit',
]);

// Must mirror ITALIAN_DRILL_VARIATIONS in src/data/mapLocations.ts (order matters).
const ITALIAN = [
  { variationId: 'giuoco-piano', drillFileId: 'giuoco-piano-main', openingId: 'italian' },
  { variationId: 'giuoco-pianissimo', drillFileId: 'giuoco-pianissimo-main', openingId: 'italian' },
  { variationId: 'two-knights', drillFileId: 'two-knights-main', openingId: 'italian' },
  { variationId: 'evans-gambit', drillFileId: 'evans-gambit-main', openingId: 'italian' },
  { variationId: 'greco-counter-attack', drillFileId: 'greco-counter-attack-main', openingId: 'italian' },
];

// Must mirror prefixFor in getKingdomDrills (src/data/kingdomDrills.ts).
const PREFIXES = {
  spanish: ['ruy-lopez-'],
  french: ['french-'],
  germany: ['caro-'],
  sicilian: ['sicilian-'],
  english: ['english-'],
  dutch: ['dutch-'],
  scandinavian: ['scandinavian-'],
  queendom: ['queen-', 'slav-', 'budapest-', 'blackmar-', 'london-'],
};

function slotsForPack({ openingId, variationId, drillFileId }) {
  const pack = JSON.parse(readFileSync(join(DRILL_DIR, `${drillFileId}.json`), 'utf8'));
  const line = (pack.lines || [])[0];
  if (!line || !Array.isArray(line.moves)) throw new Error(`${drillFileId}: no lines[0].moves`);
  const fen = line.startFen || pack.startFen || '';
  const startSide = fen.split(' ')[1] === 'b' ? 'black' : 'white';
  return line.moves.map((_, i) => ({
    key: `${openingId}:${variationId}:${i}`,
    side: i % 2 === 0 ? startSide : startSide === 'white' ? 'black' : 'white',
  }));
}

const result = { italian: ITALIAN.map((v) => ({ variationId: v.variationId, slots: slotsForPack(v) })) };

for (const [kingdom, prefixes] of Object.entries(PREFIXES)) {
  result[kingdom] = ALL_IDS.filter(
    (id) => id.endsWith('-main') && !DEMOTED.has(id.replace(/-main$/, '')) && prefixes.some((p) => id.startsWith(p)),
  ).map((id) => {
    const variationId = id.replace(/-main$/, '');
    return { variationId, slots: slotsForPack({ openingId: kingdom, variationId, drillFileId: id }) };
  });
}

const body = Object.entries(result)
  .map(([kingdom, variations]) => {
    const vars = variations
      .map((v) => `    { variationId: '${v.variationId}', slots: ${JSON.stringify(v.slots)} },`)
      .join('\n');
    return `  ${kingdom}: [\n${vars}\n  ],`;
  })
  .join('\n');

const out = `/**
 * GENERATED by scripts/compute-kingdom-slots.mjs — DO NOT EDIT MANUALLY.
 * Per-variation move-slot sets for the story-progression cleared predicates.
 * Re-run the generator after drill-registry or main-pack changes.
 */
import type { MoveSlot } from '../../shared/progressRules';

export interface KingdomVariationSlots {
  variationId: string;
  slots: MoveSlot[];
}

export const KINGDOM_VARIATION_SLOTS: Partial<Record<string, KingdomVariationSlots[]>> = {
${body}
};
`;

writeFileSync(OUT_FILE, out);
for (const [kingdom, variations] of Object.entries(result)) {
  const total = variations.reduce((n, v) => n + v.slots.length, 0);
  console.log(`${kingdom}: ${variations.length} variations, ${total} slots (first: ${variations[0]?.variationId ?? '—'})`);
}
console.log(`Wrote ${OUT_FILE}`);
